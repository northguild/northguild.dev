// Bakes a small lunar albedo map for the aurora's moon from NASA SVS's CGI
// Moon Kit (LRO colour map, longitude 0 at the centre, east to the right).
// Writes apps/site/src/scripts/aurora.moon.ts: 128×64 greyscale, base64.
//
// Run: node scripts/build-moon.mjs
// Moon: NASA's Scientific Visualization Studio.

import { writeFileSync } from "node:fs";
import jpeg from "jpeg-js";

const SOURCE =
  "https://svs.gsfc.nasa.gov/vis/a000000/a004700/a004720/lroc_color_poles_1k.jpg";
const W = 128;
const H = 64;
const OUT = new URL("../apps/site/src/scripts/aurora.moon.ts", import.meta.url);

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`moon map: HTTP ${res.status}`);
const img = jpeg.decode(Buffer.from(await res.arrayBuffer()), {
  useTArray: true,
});

// Box-filter down to W×H luminance.
const out = new Uint8Array(W * H);
const sx = img.width / W;
const sy = img.height / H;
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    let sum = 0;
    let n = 0;
    for (let j = Math.floor(y * sy); j < Math.floor((y + 1) * sy); j++) {
      for (let i = Math.floor(x * sx); i < Math.floor((x + 1) * sx); i++) {
        const o = (j * img.width + i) * 4;
        sum +=
          0.2126 * img.data[o] +
          0.7152 * img.data[o + 1] +
          0.0722 * img.data[o + 2];
        n++;
      }
    }
    out[y * W + x] = Math.round(sum / n);
  }
}

writeFileSync(
  OUT,
  `// Generated by scripts/build-moon.mjs from NASA SVS's CGI Moon Kit. Do not edit.
// ${W}×${H} greyscale albedo, equirectangular, longitude 0 at the centre.
export const MOON = {
  width: ${W},
  height: ${H},
  data: "${Buffer.from(out).toString("base64")}",
};
`,
);
console.log(`${W}×${H}, ${out.length} bytes`);
